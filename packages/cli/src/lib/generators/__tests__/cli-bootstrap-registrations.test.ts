describe('generateModuleRegistry writes bootstrap-registrations.cli.generated.ts', () => {
  let tmpDir: string
  let outputDir: string
  let fileMtimeNonce = 0

  function touchFile(filePath: string, content = ''): void {
    fs.mkdirSync(path.dirname(filePath), { recursive: true })
    fs.writeFileSync(filePath, content)
    const mtime = new Date(Date.now() + fileMtimeNonce)
    fileMtimeNonce += 1
    fs.utimesSync(filePath, mtime, mtime)
  }

  function pkgModulePath(moduleId: string, ...segments: string[]): string {
    return path.join(tmpDir, 'packages', 'core', 'src', 'modules', moduleId, ...segments)
  }

  function createMockResolver(enabled: ModuleEntry[]): PackageResolver {
    return {
      isMonorepo: () => true,
      getRootDir: () => tmpDir,
      getAppDir: () => path.join(tmpDir, 'app'),
      getOutputDir: () => outputDir,
      getModulesConfigPath: () => path.join(tmpDir, 'app', 'src', 'modules.ts'),
      discoverPackages: () => [],
      loadEnabledModules: () => enabled,
      getModulePaths: (entry: ModuleEntry) => ({
        appBase: path.join(tmpDir, 'app', 'src', 'modules', entry.id),
        pkgBase: pkgModulePath(entry.id),
      }),
      getModuleImportBase: (entry: ModuleEntry) => ({
        appBase: `@/modules/${entry.id}`,
        pkgBase: `@open-mercato/core/modules/${entry.id}`,
      }),
      getPackageOutputDir: () => outputDir,
      getPackageRoot: () => path.join(tmpDir, 'packages', 'core'),
    }
  }

  function readGenerated(filename: string): string | null {
    const filePath = path.join(outputDir, filename)
    if (!fs.existsSync(filePath)) return null
    return fs.readFileSync(filePath, 'utf8')
  }

  function scaffoldPluginModule(): ModuleEntry[] {
    touchFile(pkgModulePath('cli_ext', 'index.ts'), "export const metadata = { id: 'cli_ext', label: 'CLI ext' }\n")
    touchFile(pkgModulePath('cli_ext', 'worker-hooks.ts'), 'export default []\n')
    touchFile(pkgModulePath('cli_ext', 'page-hooks.ts'), 'export default []\n')
    touchFile(pkgModulePath('cli_ext', 'generators.ts'), GENERATORS_FIXTURE)
    return [{ id: 'cli_ext', from: '@open-mercato/core' }]
  }

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cli-bootstrap-registrations-'))
    outputDir = path.join(tmpDir, 'app', '.mercato', 'generated')
    fs.mkdirSync(outputDir, { recursive: true })
    fileMtimeNonce = 0
  })

  afterEach(() => {
    fs.rmSync(tmpDir, { recursive: true, force: true })
  })

  it('writes only the registrations of plugins that opt in with bootstrapRegistration.cli', async () => {
    const resolver = createMockResolver(scaffoldPluginModule())

    const result = await generateModuleRegistry({ resolver, quiet: true })

    expect(result.errors).toEqual([])
    const cliContent = readGenerated(CLI_FILE)
    expect(cliContent).not.toBeNull()
    const content = cliContent ?? ''
    expectNoSyntaxErrors(content)
    expect(isExportedVoidFunction(content)).toBe(true)
    expect(parseImports(content)).toEqual([
      { moduleSpecifier: './cli-ext-worker-hooks.generated', names: ['workerHookEntries'] },
      { moduleSpecifier: '@open-mercato/core/modules/cli_ext/lib/worker-hooks', names: ['registerWorkerHooks'] },
    ])
    expect(parseRegistrationCalls(content)).toEqual(['registerWorkerHooks(workerHookEntries)'])
    expect(content).not.toContain('pageHookEntries')
    expect(content).not.toContain('optedOutHookEntries')
    expect(content).not.toContain('registerBackendRouteManifests')
    expect(content).not.toContain('registerFrontendRouteManifests')
  })

  it('keeps every plugin registration plus the route manifests in bootstrap-registrations.generated.ts', async () => {
    const resolver = createMockResolver(scaffoldPluginModule())

    await generateModuleRegistry({ resolver, quiet: true })

    const appContent = readGenerated(APP_FILE)
    expect(appContent).not.toBeNull()
    const calls = parseRegistrationCalls(appContent ?? '', 'runBootstrapRegistrations')
    expect(calls).toEqual(expect.arrayContaining([
      'registerBackendRouteManifests(backendRouteFacades)',
      'registerFrontendRouteManifests(frontendRoutes)',
      'registerWorkerHooks(workerHookEntries)',
      'registerPageHooks(pageHookEntries)',
      'registerOptedOutHooks(optedOutHookEntries)',
    ]))
    expect(calls).toHaveLength(5)
  })

  it('always writes the CLI file, as an empty registration, when no module declares a plugin', async () => {
    const resolver = createMockResolver([])

    await generateModuleRegistry({ resolver, quiet: true })

    const cliContent = readGenerated(CLI_FILE)
    expect(cliContent).not.toBeNull()
    const content = cliContent ?? ''
    expectNoSyntaxErrors(content)
    expect(isExportedVoidFunction(content)).toBe(true)
    expect(parseImports(content)).toEqual([])
    expect(parseRegistrationCalls(content)).toEqual([])
    expect(fs.existsSync(path.join(outputDir, 'bootstrap-registrations.cli.generated.checksum'))).toBe(true)
  })

  it('drops a registration from the CLI file once its module is disabled', async () => {
    await generateModuleRegistry({ resolver: createMockResolver(scaffoldPluginModule()), quiet: true })
    expect(parseRegistrationCalls(readGenerated(CLI_FILE) ?? '')).toEqual(['registerWorkerHooks(workerHookEntries)'])

    await generateModuleRegistry({ resolver: createMockResolver([]), quiet: true })

    expect(parseRegistrationCalls(readGenerated(CLI_FILE) ?? '')).toEqual([])
    expect(parseImports(readGenerated(CLI_FILE) ?? '')).toEqual([])
  })

  it('is idempotent across regenerations', async () => {
    const resolver = createMockResolver(scaffoldPluginModule())

    await generateModuleRegistry({ resolver, quiet: true })
    const firstRun = readGenerated(CLI_FILE)
    await generateModuleRegistry({ resolver, quiet: true })

    expect(readGenerated(CLI_FILE)).toBe(firstRun)
  })
})
