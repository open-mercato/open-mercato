/**
 * Contract tests for `bootstrap-registrations.cli.generated.ts`: the renderer
 * (`renderCliBootstrapRegistrationsFile`) and the registry generator that writes it with only the
 * generator-plugin registrations that opt in via `bootstrapRegistration.cli`. CLI and worker
 * processes load this file instead of `bootstrap-registrations.generated.ts`, so it must never
 * carry the route-manifest registrations or registrations of plugins that did not opt in.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import ts from 'typescript-js'
import type { ModuleEntry, PackageResolver } from '../../resolver'
import { generateModuleRegistry, renderCliBootstrapRegistrationsFile } from '../module-registry'

const CLI_FILE = 'bootstrap-registrations.cli.generated.ts'
const APP_FILE = 'bootstrap-registrations.generated.ts'
const CLI_FUNCTION = 'runCliBootstrapRegistrations'

function parseFile(content: string): ts.SourceFile {
  return ts.createSourceFile(CLI_FILE, content, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
}

function expectNoSyntaxErrors(content: string): void {
  const sourceFile = parseFile(content)
  const diagnostics = (sourceFile as unknown as { parseDiagnostics?: ts.Diagnostic[] }).parseDiagnostics ?? []
  expect(diagnostics.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, ' '))).toEqual([])
}

function parseImports(content: string): Array<{ moduleSpecifier: string; names: string[] }> {
  return parseFile(content)
    .statements.filter(ts.isImportDeclaration)
    .map((declaration) => {
      const bindings = declaration.importClause?.namedBindings
      return {
        moduleSpecifier: (declaration.moduleSpecifier as ts.StringLiteral).text,
        names: bindings && ts.isNamedImports(bindings) ? bindings.elements.map((element) => element.name.text) : [],
      }
    })
}

function findFunction(content: string, name: string): { sourceFile: ts.SourceFile; declaration: ts.FunctionDeclaration | undefined } {
  const sourceFile = parseFile(content)
  const declaration = sourceFile.statements.find(
    (statement): statement is ts.FunctionDeclaration =>
      ts.isFunctionDeclaration(statement) && statement.name?.text === name,
  )
  return { sourceFile, declaration }
}

function parseRegistrationCalls(content: string, name = CLI_FUNCTION): string[] {
  const { sourceFile, declaration } = findFunction(content, name)
  if (!declaration) throw new Error(`[internal] ${name} declaration not found`)
  return (declaration.body?.statements ?? []).map((statement) => statement.getText(sourceFile).replace(/;$/, ''))
}

function isExportedVoidFunction(content: string, name = CLI_FUNCTION): boolean {
  const { declaration } = findFunction(content, name)
  if (!declaration) return false
  const isExported = declaration.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) ?? false
  return isExported && declaration.type?.kind === ts.SyntaxKind.VoidKeyword
}

describe('renderCliBootstrapRegistrationsFile', () => {
  it('emits an exported no-op function with no imports when no plugin opts in', () => {
    const content = renderCliBootstrapRegistrationsFile({ entryImports: [], registrationImports: [], calls: [] })

    expectNoSyntaxErrors(content)
    expect(content.startsWith('// AUTO-GENERATED by mercato generate registry\n')).toBe(true)
    expect(isExportedVoidFunction(content)).toBe(true)
    expect(parseImports(content)).toEqual([])
    expect(parseRegistrationCalls(content)).toEqual([])
    expect(findFunction(content, 'runBootstrapRegistrations').declaration).toBeUndefined()
  })

  it('emits the plugin entry import, registration import and call', () => {
    const content = renderCliBootstrapRegistrationsFile({
      entryImports: ['import { processConfigEntries } from "./insights-process.generated"'],
      registrationImports: [
        "import { registerProcessConfigEntries } from '@open-mercato/core/modules/insights/lib/process/registry'",
      ],
      calls: ['registerProcessConfigEntries(processConfigEntries)'],
    })

    expectNoSyntaxErrors(content)
    expect(isExportedVoidFunction(content)).toBe(true)
    expect(parseImports(content)).toEqual([
      { moduleSpecifier: './insights-process.generated', names: ['processConfigEntries'] },
      {
        moduleSpecifier: '@open-mercato/core/modules/insights/lib/process/registry',
        names: ['registerProcessConfigEntries'],
      },
    ])
    expect(parseRegistrationCalls(content)).toEqual(['registerProcessConfigEntries(processConfigEntries)'])
  })

  it('keeps several plugins in order, entry imports before registration imports', () => {
    const content = renderCliBootstrapRegistrationsFile({
      entryImports: [
        'import { explainConfigEntries } from "./insights-explain.generated"',
        'import { processConfigEntries } from "./insights-process.generated"',
      ],
      registrationImports: [
        "import { registerExplainConfigEntries } from '@open-mercato/core/modules/insights/lib/explain-registry'",
        "import { registerProcessConfigEntries } from '@open-mercato/core/modules/insights/lib/process/registry'",
      ],
      calls: [
        'registerExplainConfigEntries(explainConfigEntries)',
        'registerProcessConfigEntries(processConfigEntries)',
      ],
    })

    expectNoSyntaxErrors(content)
    expect(parseImports(content).map((parsed) => parsed.moduleSpecifier)).toEqual([
      './insights-explain.generated',
      './insights-process.generated',
      '@open-mercato/core/modules/insights/lib/explain-registry',
      '@open-mercato/core/modules/insights/lib/process/registry',
    ])
    expect(parseRegistrationCalls(content)).toEqual([
      'registerExplainConfigEntries(explainConfigEntries)',
      'registerProcessConfigEntries(processConfigEntries)',
    ])
  })

  it('de-duplicates identical imports contributed by several plugins but keeps every call', () => {
    const sharedRegistrationImport = "import { registerEntries } from '@open-mercato/core/modules/shared/registrations'"
    const sharedEntryImport = 'import { sharedEntries } from "./shared-entries.generated"'
    const content = renderCliBootstrapRegistrationsFile({
      entryImports: [sharedEntryImport, sharedEntryImport, 'import { otherEntries } from "./other-entries.generated"'],
      registrationImports: [sharedRegistrationImport, sharedRegistrationImport],
      calls: ['registerEntries(sharedEntries)', 'registerEntries(otherEntries)'],
    })

    expectNoSyntaxErrors(content)
    expect(parseImports(content)).toEqual([
      { moduleSpecifier: './shared-entries.generated', names: ['sharedEntries'] },
      { moduleSpecifier: './other-entries.generated', names: ['otherEntries'] },
      { moduleSpecifier: '@open-mercato/core/modules/shared/registrations', names: ['registerEntries'] },
    ])
    expect(parseRegistrationCalls(content)).toEqual(['registerEntries(sharedEntries)', 'registerEntries(otherEntries)'])
  })

  it('fails at generation time and names the statement when a plugin import is malformed', () => {
    expect(() =>
      renderCliBootstrapRegistrationsFile({
        entryImports: [],
        registrationImports: ['registerSomething from "./not-an-import"'],
        calls: ['registerSomething([])'],
      }),
    ).toThrow('Expected import declaration, received: registerSomething from "./not-an-import"')
  })
})

