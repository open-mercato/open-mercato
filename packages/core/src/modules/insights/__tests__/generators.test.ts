import fs from 'node:fs'
import path from 'node:path'
import generatorPlugins, { buildExplainConfigOutput, explainConfigPlugin } from '../generators'

describe('insights generator plugin', () => {
  it('declares the insights.explain convention and output file', () => {
    expect(generatorPlugins).toEqual([explainConfigPlugin])
    expect(explainConfigPlugin).toEqual(expect.objectContaining({
      id: 'insights.explain',
      conventionFile: 'insights.explain.ts',
      importPrefix: 'INSIGHTS_EXPLAIN',
      outputFileName: 'insights-explain.generated.ts',
    }))
  })

  it('reads the default export first and falls back to explainConfig', () => {
    expect(explainConfigPlugin.configExpr('INSIGHTS_EXPLAIN_customers_0', 'customers')).toBe(
      "{ moduleId: 'customers', config: (INSIGHTS_EXPLAIN_customers_0.default ?? INSIGHTS_EXPLAIN_customers_0.explainConfig ?? null) as unknown }",
    )
  })

  it('builds a typed entries file with and without discovered modules', () => {
    const empty = buildExplainConfigOutput({ importSection: '', entriesLiteral: '' })
    expect(empty).toBe(`// AUTO-GENERATED by mercato generate registry
type ExplainConfigEntry = { moduleId: string; config: unknown }

export const explainConfigEntries: ExplainConfigEntry[] = [
]
`)

    const populated = buildExplainConfigOutput({
      importSection: "import * as INSIGHTS_EXPLAIN_customers_0 from '@open-mercato/core/modules/customers/insights.explain'",
      entriesLiteral: explainConfigPlugin.configExpr('INSIGHTS_EXPLAIN_customers_0', 'customers'),
    })
    expect(populated).toContain("import * as INSIGHTS_EXPLAIN_customers_0 from '@open-mercato/core/modules/customers/insights.explain'")
    expect(populated).toContain("  { moduleId: 'customers', config: (INSIGHTS_EXPLAIN_customers_0.default")
  })

  it('wires a bootstrap registration through the explain registry', () => {
    const registration = explainConfigPlugin.bootstrapRegistration
    expect(registration?.entriesExportName).toBe('explainConfigEntries')
    expect(registration?.registrationImports).toEqual([
      "import { registerExplainConfigEntries } from '@open-mercato/core/modules/insights/lib/explain-registry'",
    ])
    expect(registration?.buildCall('explainConfigEntries')).toBe('registerExplainConfigEntries(explainConfigEntries)')
  })

  it('uses only type imports so the CLI can load it without runtime dependencies', () => {
    const source = fs.readFileSync(path.join(__dirname, '..', 'generators.ts'), 'utf8')
    expect(source).not.toMatch(/^import\s+(?!type\b)/m)
  })
})
