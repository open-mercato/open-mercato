import type { GeneratorPlugin } from '@open-mercato/shared/modules/generators'

export function buildExplainConfigOutput({
  importSection,
  entriesLiteral,
}: {
  importSection: string
  entriesLiteral: string
}): string {
  return `// AUTO-GENERATED by mercato generate registry
${importSection ? `${importSection}\n` : ''}type ExplainConfigEntry = { moduleId: string; config: unknown }

export const explainConfigEntries: ExplainConfigEntry[] = [
${entriesLiteral ? `  ${entriesLiteral}\n` : ''}]
`
}

/**
 * Lets any module contribute "Why?" explain declarations by exporting `insights.explain.ts`
 * (`export const explainConfig = defineExplainConfig({ version: 1, ... })`). The generator
 * aggregates them and wires a bootstrap registration call, so the insights explain registry is
 * populated at boot without insights knowing about individual modules.
 */
export const explainConfigPlugin: GeneratorPlugin = {
  id: 'insights.explain',
  conventionFile: 'insights.explain.ts',
  importPrefix: 'INSIGHTS_EXPLAIN',
  configExpr: (importName: string, moduleId: string) =>
    `{ moduleId: '${moduleId}', config: (${importName}.default ?? ${importName}.explainConfig ?? null) as unknown }`,
  outputFileName: 'insights-explain.generated.ts',
  buildOutput: buildExplainConfigOutput,
  bootstrapRegistration: {
    entriesExportName: 'explainConfigEntries',
    registrationImports: [
      `import { registerExplainConfigEntries } from '@open-mercato/core/modules/insights/lib/explain-registry'`,
    ],
    buildCall: (name: string) => `registerExplainConfigEntries(${name})`,
  },
}

export const generatorPlugins: GeneratorPlugin[] = [explainConfigPlugin]

export default generatorPlugins
