import type { GeneratorPlugin } from '@open-mercato/shared/modules/generators'

export function buildExplainConfigOutput({
  importSection,
  entriesLiteral,
}: {
  importSection: string
  entriesLiteral: string
}): string {
  return `// AUTO-GENERATED by mercato generate registry
${importSection ? `${importSection}\n` : ''}type ExplainConfigEntry = { moduleId: string; config: unknown }

export const explainConfigEntries: ExplainConfigEntry[] = [
${entriesLiteral ? `  ${entriesLiteral}\n` : ''}]
`
}

export function buildProcessConfigOutput({
  importSection,
  entriesLiteral,
}: {
  importSection: string
  entriesLiteral: string
}): string {
  return `// AUTO-GENERATED by mercato generate registry
${importSection ? `${importSection}\n` : ''}type ProcessConfigEntry = { moduleId: string; config: unknown }

export const processConfigEntries: ProcessConfigEntry[] = [
${entriesLiteral ? `  ${entriesLiteral}\n` : ''}]
`
}

/**
 * Lets any module contribute "Why?" explain declarations by exporting `insights.explain.ts`
 * (`export const explainConfig = defineExplainConfig({ version: 1, ... })`). The generator
 * aggregates them and wires a bootstrap registration call, so the insights explain registry is
 * populated at boot without insights knowing about individual modules.
 */
export const explainConfigPlugin: GeneratorPlugin = {
  id: 'insights.explain',
  conventionFile: 'insights.explain.ts',
  importPrefix: 'INSIGHTS_EXPLAIN',
  configExpr: (importName: string, moduleId: string) =>
    `{ moduleId: '${moduleId}', config: (${importName}.default ?? ${importName}.explainConfig ?? null) as unknown }`,
  outputFileName: 'insights-explain.generated.ts',
  buildOutput: buildExplainConfigOutput,
  bootstrapRegistration: {
    entriesExportName: 'explainConfigEntries',
    registrationImports: [
      `import { registerExplainConfigEntries } from '@open-mercato/core/modules/insights/lib/explain-registry'`,
    ],
    buildCall: (name: string) => `registerExplainConfigEntries(${name})`,
    cli: true,
  },
}

/**
 * Both insights registries are read by CLI commands (`explain:coverage`, `xray:*`) and the
 * X-Ray workers, so their registrations also run in CLI/worker processes (`cli: true`).
 *
 * Lets any module contribute Process X-Ray declarations by exporting `insights.process.ts`
 * (`export const processConfig = defineProcessConfig({ version: 1, ... })`). The registry
 * validates them against the owning modules' encryption maps once the module registry is
 * bootstrapped and rejects declarations that would copy encrypted values into plaintext.
 */
export const processConfigPlugin: GeneratorPlugin = {
  id: 'insights.process',
  conventionFile: 'insights.process.ts',
  importPrefix: 'INSIGHTS_PROCESS',
  configExpr: (importName: string, moduleId: string) =>
    `{ moduleId: '${moduleId}', config: (${importName}.default ?? ${importName}.processConfig ?? null) as unknown }`,
  outputFileName: 'insights-process.generated.ts',
  buildOutput: buildProcessConfigOutput,
  bootstrapRegistration: {
    entriesExportName: 'processConfigEntries',
    registrationImports: [
      `import { registerProcessConfigEntries } from '@open-mercato/core/modules/insights/lib/process/registry'`,
    ],
    buildCall: (name: string) => `registerProcessConfigEntries(${name})`,
    cli: true,
  },
}

export const generatorPlugins: GeneratorPlugin[] = [explainConfigPlugin, processConfigPlugin]

export default generatorPlugins
