#!/usr/bin/env node
/**
 * Build-time generator: extracts ISO alpha-2 region subtags from
 * language-subtag-registry into a small TypeScript module so the published
 * package never imports the registry JSON at runtime (Node ESM requires
 * `with { type: 'json' }`, which esbuild strips when bundle:false).
 */
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageDir = fileURLToPath(new URL('..', import.meta.url))
const require = createRequire(join(packageDir, 'package.json'))
const registry = require('language-subtag-registry/data/json/registry.json')

/**
 * @typedef {{ Type: string, Subtag?: string, Description?: string[], Deprecated?: string }} RegistryEntry
 */

/** @param {RegistryEntry} entry */
function isIsoAlpha2(entry) {
  if (entry.Type !== 'region') return false
  if (!entry.Subtag || !/^[A-Z]{2}$/.test(entry.Subtag)) return false
  if (entry.Deprecated) return false
  if (!entry.Description || !entry.Description.length) return false
  if (entry.Description[0] === 'Private use') return false
  return true
}

const countries = /** @type {RegistryEntry[]} */ (registry)
  .filter(isIsoAlpha2)
  .map((entry) => ({
    code: /** @type {string} */ (entry.Subtag),
    name: /** @type {string[]} */ (entry.Description).join(', '),
  }))
  .sort((a, b) => a.code.localeCompare(b.code))

const lines = [
  '// AUTO-GENERATED by scripts/generate-countries.mjs — do not edit by hand.',
  '// Regenerate via `node packages/shared/scripts/generate-countries.mjs` or the shared package build.',
  '',
  'export const REGISTRY_COUNTRIES: Array<{ code: string; name: string }> = [',
  ...countries.map((c) => `  { code: ${JSON.stringify(c.code)}, name: ${JSON.stringify(c.name)} },`),
  ']',
  '',
]

const outPath = join(packageDir, 'src/lib/location/countries.generated.ts')
writeFileSync(outPath, lines.join('\n'), 'utf8')
console.log(`[generate-countries] wrote ${countries.length} countries → ${outPath}`)
