import { expect } from '@playwright/test'

export const financeWidgetKinds = ['stock-market-tracker','my-cards','spending-summary','my-cards-vertical','major-expenses','credit-score','total-balance','total-expenses','exchange','currency-list','recent-transactions','my-subscriptions','quick-transfer','donation-profile','saved-actions','budget-overview']

export async function checkFinanceWidgets(page, render, artifacts, themes = ['light','dark']) {
  const measurements = []
  const renderKind = (kind, theme, empty = false) => render(page, `backend-charts-finance-widgets--variant-${kind}${empty ? '-empty' : ''}`, `theme:${theme};locale:en`)
  for (const theme of themes) {
    await page.setViewportSize({ width: 1280, height: 1000 })
    for (const kind of financeWidgetKinds) for (const empty of [false,true]) {
      await renderKind(kind,theme,empty)
      const widget = page.locator('[data-slot="finance-widget"]')
      await expect(widget).toBeVisible()
      const geometry = await widget.evaluate(element => ({ width: element.getBoundingClientRect().width, height: element.getBoundingClientRect().height, overflowY: element.scrollHeight - element.clientHeight, brokenImages: [...element.querySelectorAll('img')].filter(image => image.complete && image.naturalWidth === 0).length, unresolvedLabels: element.innerText.includes('design_system.gallery.samples.finance.') }))
      expect(geometry.width,kind).toBe(kind==='budget-overview'?728:352)
      expect(geometry.height,kind).toBe(kind==='my-cards-vertical'?784:['major-expenses','credit-score','total-balance','total-expenses'].includes(kind)?178:380)
      expect(geometry.overflowY,kind).toBeLessThanOrEqual(1)
      expect(geometry.brokenImages,kind).toBe(0)
      expect(geometry.unresolvedLabels,kind).toBe(false)
      measurements.push({theme,kind,empty,...geometry})
      await widget.screenshot({path:`${artifacts}/finance-${kind}${empty?'-empty':''}-${theme}.png`})
    }
    await renderKind('stock-market-tracker',theme,true)
    await page.getByRole('button',{name:'Refresh',exact:true}).click()
    await expect(page.locator('[data-slot="finance-empty"]')).toHaveCount(0)
    await page.getByRole('radio',{name:'1D',exact:true}).click()
    await expect(page.getByRole('radio',{name:'1D',exact:true})).toBeChecked()
    await renderKind('my-cards-vertical',theme)
    await page.getByRole('button',{name:'Unhide',exact:true}).click()
    await expect(page.getByText('5489 1200 3456 1234',{exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Adjust Limit',exact:true}).click()
    await page.getByRole('dialog').getByRole('spinbutton').fill('2300')
    await page.getByRole('dialog').press('Control+Enter')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByText('$2,300.00',{exact:true})).toBeVisible()
    await renderKind('currency-list',theme)
    await page.getByRole('searchbox').fill('JPY')
    await expect(page.getByText('Japanese Yen',{exact:true})).toBeVisible()
    await expect(page.getByText('Canadian Dollar',{exact:true})).toHaveCount(0)
    await page.getByRole('button',{name:'Clear search',exact:true}).click()
    await expect(page.getByText('Canadian Dollar',{exact:true})).toBeVisible()
    await renderKind('exchange',theme)
    await page.getByRole('spinbutton',{name:'Amount',exact:true}).fill('200')
    await expect(page.getByText('€182.36',{exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Exchange',exact:true}).click()
    await expect(page.getByRole('button',{name:'Sample exchange completed',exact:true})).toBeVisible()
    await page.getByRole('spinbutton',{name:'Amount',exact:true}).fill('-1')
    await expect(page.getByRole('button',{name:'Exchange',exact:true})).toBeDisabled()
    await renderKind('recent-transactions',theme)
    await page.getByRole('radio',{name:'Outgoing',exact:true}).click()
    await expect(page.getByRole('button',{name:/Grocery Shopping/})).toBeVisible()
    await expect(page.getByRole('button',{name:/Salary Deposit/})).toHaveCount(0)
    await page.getByRole('button',{name:/Grocery Shopping/}).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await renderKind('quick-transfer',theme)
    await expect(page.getByRole('button',{name:'Save a New Action',exact:true})).toBeDisabled()
    await page.getByRole('spinbutton').fill('25')
    await page.getByRole('button',{name:'Save a New Action',exact:true}).click()
    await expect(page.getByRole('button',{name:'Sample action saved',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Next contacts',exact:true}).click()
    await expect(page.getByRole('button',{name:'James',exact:true})).toBeVisible()
    await renderKind('my-subscriptions',theme)
    await page.getByRole('button',{name:'Manage Spotify',exact:true}).click()
    await page.getByRole('button',{name:'Pause',exact:true}).click()
    await page.keyboard.press('Escape')
    await expect(page.getByText('Paused',{exact:true})).toHaveCount(2)
    await renderKind('donation-profile',theme,true)
    await page.getByRole('button',{name:'Donate',exact:true}).click()
    await page.getByRole('dialog').getByRole('spinbutton').fill('250')
    await page.getByRole('dialog').getByRole('button',{name:'Donate',exact:true}).click()
    await expect(page.getByText('$250.00',{exact:true})).toBeVisible()
    await expect(page.getByText('Donations in the last year: 1',{exact:true})).toBeVisible()
    await page.getByRole('radio',{name:'Goal',exact:true}).click()
    await expect(page.getByRole('progressbar').first()).toBeVisible()
    await page.setViewportSize({width:375,height:900})
    for (const kind of financeWidgetKinds) {
      await renderKind(kind,theme)
      const size = await page.locator('[data-slot="finance-widget"]').evaluate(element=>({width:element.getBoundingClientRect().width,overflowY:element.scrollHeight-element.clientHeight,viewport:document.documentElement.clientWidth,page:document.documentElement.scrollWidth}))
      expect(size.width,kind).toBeLessThanOrEqual(375)
      expect(size.page,kind).toBeLessThanOrEqual(size.viewport+1)
      expect(size.overflowY,kind).toBeLessThanOrEqual(1)
    }
  }
  return measurements
}
