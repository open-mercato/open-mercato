import assert from 'node:assert/strict'
import path from 'node:path'
import { expect } from '@playwright/test'
import { readGallery } from '../packages/create-app/scripts/design-system-sources.mjs'

const compact = new Set(['product-categories','customer-segments','sales-channels','campaign-data'])
const tall = new Set(['support-analytics','recent-activities'])

export async function checkMarketingWidgets(page,render,artifacts) {
  const {entries}=readGallery(process.cwd())
  const widgets=entries.find(entry=>entry.entryId==='marketing-widgets').variantIds
  const controls=entries.find(entry=>entry.entryId==='marketing-controls').variantIds
  assert.equal(widgets.length,18)
  assert.equal(controls.length,54)
  const checks=[]
  for(const theme of ['light','dark']) {
    const globals=`theme:${theme};font:application`
    const showWidget=kind=>render(page,`backend-charts-marketing-widgets--variant-${kind}`,globals)
    const showControl=kind=>render(page,`primitives-inputs-marketing-controls--variant-${kind}`,globals)
    for(const kind of widgets) {
      await showWidget(kind)
      const widget=page.locator('[data-slot=marketing-widget]')
      const bounds=await widget.boundingBox()
      assert.equal(bounds.width,352)
      assert.equal(bounds.height,tall.has(kind)?784:compact.has(kind)?178:380)
      await expect(widget).toHaveCSS('border-radius','16px')
      if(kind==='geography') assert.equal(await widget.locator('[data-slot=marketing-map] span[aria-hidden=true]').first().evaluate(node=>node.getBoundingClientRect().width),332)
      if(kind==='support-analytics') for(const tab of await widget.getByRole('tab').all()) assert.ok(await tab.evaluate(node=>[...node.querySelectorAll('span')].every(span=>span.scrollWidth<=span.clientWidth)))
      assert.equal((await widget.innerText()).includes('design_system.'),false,kind)
      for(const img of await widget.locator('img').all()) await expect.poll(()=>img.evaluate(node=>node.complete&&node.naturalWidth>0)).toBe(true)
      if(artifacts)await widget.screenshot({animations:'disabled',path:path.join(artifacts,`${kind}-${theme}.png`)})
    }
    for(const kind of controls) {
      await showControl(kind)
      const control=page.locator('[data-slot=marketing-control]')
      await expect(control).toHaveCount(1)
      assert.equal((await control.innerText()).includes('design_system.'),false,kind)
      if(kind.startsWith('product-image'))await expect.poll(()=>control.evaluate(node=>node.complete&&node.naturalWidth===200)).toBe(true)
      if(kind.startsWith('input-')||kind.startsWith('amount-')||kind.startsWith('textarea-')||kind.startsWith('select-')) {
        const bounds=await control.boundingBox()
        assert.equal(bounds.width,372)
        assert.equal(bounds.height,kind.startsWith('amount-')||kind.endsWith('large')?80:64)
      }
      if(kind==='selected-button-selected') assert.ok(await control.evaluate(node=>{
        const probe=document.createElement('span')
        probe.style.backgroundColor='color-mix(in oklab, var(--accent-orange) 10%, transparent)'
        document.body.appendChild(probe)
        const expected=getComputedStyle(probe).backgroundColor
        probe.remove()
        return getComputedStyle(node).backgroundColor===expected
      }))
      if(kind.endsWith('disabled')) assert.ok(await control.evaluate(node=>node.matches(':disabled')||Boolean(node.querySelector(':disabled'))))
      if(artifacts)await page.locator('.om-story-surface').screenshot({animations:'disabled',path:path.join(artifacts,`control-${kind}-${theme}.png`)})
    }
    await showWidget('total-sales')
    await page.getByRole('radio',{name:'1M',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('$256.64')
    await page.getByRole('button',{name:'Report',exact:true}).click()
    await expect(page.getByRole('dialog')).toContainText('Online Store')
    await page.keyboard.press('Control+Enter')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await showWidget('user-retention')
    await page.getByRole('button',{name:'Cohort 1, month 1: 100%',exact:true}).click()
    await expect(page.locator('[aria-live=polite]')).toContainText('Cohort 1, month 1: 100%')
    await showWidget('weekly-visitors')
    await page.getByRole('button',{name:'New visitors',exact:true}).click()
    await expect(page.getByRole('button',{name:'New visitors',exact:true})).toHaveAttribute('aria-pressed','false')
    await showWidget('geography')
    await page.getByRole('button',{name:'United States',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('8,530')
    await page.getByRole('button',{name:'Zoom in',exact:true}).click()
    await expect(page.getByRole('button',{name:'Zoom out',exact:true})).toBeEnabled()
    await page.getByRole('button',{name:'Reset map',exact:true}).click()
    await expect(page.getByRole('button',{name:'Zoom out',exact:true})).toBeDisabled()
    await expect(page.getByRole('button',{name:'Turkey',exact:true})).toHaveAttribute('aria-pressed','true')
    await showWidget('product-performance')
    await page.getByRole('radio',{name:'1D',exact:true}).press('Space')
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('13.7%')
    await showWidget('shipping-tracking')
    await page.getByRole('radio',{name:'Returned',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('769')
    await page.getByRole('button',{name:'Next product',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('Macbook')
    await page.getByRole('combobox',{name:'Period',exact:true}).click()
    await page.getByRole('option',{name:'Monthly',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('2,306')
    await showWidget('my-products')
    await page.getByRole('searchbox').fill('AirPods')
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('AirPods Max Green')
    await expect(page.locator('[data-slot=marketing-widget]')).not.toContainText('iMac')
    await page.getByRole('searchbox').fill('not-a-product')
    await expect(page.getByRole('status')).toHaveText('No products match your search.')
    await showWidget('product-categories')
    await page.getByRole('button',{name:'Next category',exact:true}).click()
    await expect(page.getByRole('meter')).toHaveAttribute('aria-valuenow','72')
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('Computers')
    await showWidget('sales-channels')
    await page.getByRole('combobox',{name:'Period',exact:true}).click()
    await page.getByRole('option',{name:'Monthly',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('984')
    await showWidget('support-analytics')
    await page.getByRole('tab',{name:'Open Tickets',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).not.toContainText('James Brown')
    await page.getByRole('button',{name:/Sophia Williams/}).click()
    await page.getByRole('button',{name:'Resolve ticket',exact:true}).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.locator('[data-slot=marketing-widget]')).not.toContainText('Sophia Williams')
    await page.getByRole('tab',{name:'Solved Tickets',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('Sophia Williams')
    await page.getByRole('radio',{name:'Billing',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('3,063')
    await showWidget('recent-activities')
    await page.getByRole('searchbox').fill('Price Change')
    await expect(page.locator('[data-slot=marketing-widget]')).not.toContainText('Inventory Updated')
    await page.getByRole('searchbox').fill('nothing-found')
    await expect(page.getByRole('status')).toHaveText('No activities match your search.')
    await page.getByRole('searchbox').fill('')
    await page.getByRole('radio',{name:'Yesterday',exact:true}).click()
    await expect(page.locator('[data-slot=marketing-widget]')).toContainText('Price Change')
    await expect(page.locator('[data-slot=marketing-widget]')).not.toContainText('New Product Added')

    await showControl('input-default-medium')
    await page.getByRole('textbox',{name:'Product name',exact:true}).fill('Local product')
    await expect(page.getByRole('textbox')).toHaveValue('Local product')
    await showControl('amount-default')
    await page.getByRole('spinbutton',{name:'Product pricing',exact:true}).fill('-10')
    assert.equal(await page.getByRole('spinbutton').evaluate(node=>node.validity.rangeUnderflow),true)
    await page.getByRole('spinbutton').fill('99.99')
    assert.equal(await page.getByRole('spinbutton').evaluate(node=>node.checkValidity()),true)
    await showControl('chart-tooltip-right')
    await expect(page.getByRole('tooltip')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('tooltip')).toHaveCount(0)
    await showControl('inline-input-placeholder')
    await page.getByRole('button',{name:'Enter your name...',exact:true}).click()
    await page.getByRole('textbox',{name:'Name',exact:true}).fill('Local name')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button',{name:'Enter your name...',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Enter your name...',exact:true}).click()
    await page.getByRole('textbox',{name:'Name',exact:true}).fill('Local name')
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button',{name:'Local name',exact:true})).toBeVisible()
    await showControl('inline-select-placeholder')
    await page.getByRole('combobox',{name:'Language',exact:true}).focus()
    await page.keyboard.press('ArrowDown')
    await page.getByRole('option',{name:'Polish',exact:true}).click()
    await expect(page.getByRole('combobox')).toHaveText('Polish')
    await showControl('select-default')
    await page.getByRole('combobox',{name:'Category',exact:true}).click()
    await page.getByRole('option',{name:'Computers',exact:true}).click()
    await expect(page.getByRole('combobox')).toHaveText('Computers')
    await showControl('selected-button-default')
    await page.getByRole('button',{name:'800',exact:true}).press('Space')
    await expect(page.getByRole('button',{name:'800',exact:true})).toHaveAttribute('aria-pressed','true')
    await showControl('tab-menu-default')
    await page.getByRole('button',{name:'Account Settings',exact:true}).press('Space')
    await expect(page.getByRole('button',{name:'Account Settings',exact:true})).toHaveAttribute('aria-pressed','true')
    await showControl('step-item-default')
    await page.locator('[data-kind=step-item]').press('Space')
    await expect(page.locator('[data-kind=step-item]')).toHaveAttribute('aria-pressed','true')
    checks.push(`Marketing: all 18 widgets and 54 source controls/assets render in ${theme}; period, map, cohorts, search, tickets, keyboard selection and inline save/cancel pass`)
  }
  await page.setViewportSize({width:390,height:1000})
  for(const kind of widgets) {
    await render(page,`backend-charts-marketing-widgets--variant-${kind}`,'theme:light;font:application')
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),kind)
    if(artifacts)await page.screenshot({animations:'disabled',path:path.join(artifacts,`${kind}-mobile.png`)})
  }
  checks.push('All 18 Marketing & Sales layouts fit a 390px viewport')
  return checks
}
