import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const artwork = [
  ['records', 'No records'],
  ['search', 'No search results'],
  ['files', 'No files'],
  ['messages', 'No messages'],
].map(([kind, name]) => ({
  id: `mercato-${kind}`,
  key: `mercato-${kind}`,
  name,
  group: 'mercato',
  src: `data:image/png;base64,${readFileSync(new URL(`packages/ui/src/assets/open-mercato-empty-states/${kind}.png`, root)).toString('base64')}`,
}))

const output = fileURLToPath(new URL('packages/ui/src/assets/mercato-empty-state-illustrations.generated.ts', root))
const source = `// Generated by scripts/generate-mercato-empty-artwork.mjs. Do not edit.\nexport const mercatoEmptyStateIllustrations = ${JSON.stringify(artwork, null, 2)} as const\n`
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== source) throw new Error('[internal] Empty-state artwork is out of sync')
} else {
  writeFileSync(output, source)
}
console.log(`Open Mercato empty states: ${artwork.length} illustrations${process.argv.includes('--check') ? ' in sync' : ' generated'}.`)
