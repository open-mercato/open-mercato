import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { readGallery } from '../packages/create-app/scripts/design-system-sources.mjs'
import { buildFigmaLibrary } from './storybook-figma-library.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.join(root, 'packages/ui/.storybook/generated')
const { families, entries } = readGallery(root)
const locale = JSON.parse(fs.readFileSync(path.join(root, 'packages/core/src/modules/design_system/i18n/en.json'), 'utf8'))
const slug = (value) => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const pascal = (value) => value.split(/[^a-zA-Z0-9]/).map(word => word.charAt(0).toUpperCase() + word.slice(1)).join('')
const primitiveFamilies = new Set(['buttons', 'inputs', 'dates', 'feedback', 'overlays', 'navigation', 'display'])
const files = new Map()
const catalogue = []

for (const entry of entries) {
  const family = families.find(candidate => candidate.id === entry.familyId)
  const familyTitle = locale[family.labelKey] ?? pascal(family.id)
  const group = ['library', 'foundations', 'icons'].includes(family.id) ? 'Foundations' : primitiveFamilies.has(family.id) ? 'Primitives' : 'Backend'
  const title = group === 'Foundations' ? `${group}/${entry.title}` : `${group}/${familyTitle}/${entry.title}`
  const id = slug(`${group}-${family.id}-${entry.entryId}`)
  const camelId = entry.entryId.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
  const description = locale[`design_system.entries.${camelId}.description`] ?? locale[`design_system.entries.${entry.entryId.replaceAll('-', '_')}.description`] ?? locale[`design_system.entries.${entry.entryId}.description`] ?? `${entry.title} — live variants from the Open Mercato library.`
  catalogue.push({ id: entry.entryId, title: entry.title, family: family.id, familyTitle, group, description, variantCount: entry.variantIds.length, storyId: `${id}--overview`, ...(entry.figmaNodeId ? { figmaNodeId: entry.figmaNodeId } : {}) })
  const lines = [
    '// Generated by yarn storybook:generate. Edit the gallery entry, not this file.',
    "import type { Meta, StoryObj } from '@storybook/nextjs-vite'",
    "import { EntryOverview, EntryVariant } from '../EntryPreview'",
    `import { entries } from '../../../core/src/modules/design_system/gallery/entries/${family.id}'`,
    `const entry = entries.find(item => item.id === ${JSON.stringify(entry.entryId)})!`,
    `const meta = { id: ${JSON.stringify(id)}, title: ${JSON.stringify(title)}, tags: ['autodocs'], parameters: { docs: { description: { component: ${JSON.stringify(description)} } } } } satisfies Meta`,
    'export default meta',
    'type Story = StoryObj<typeof meta>',
    'export const Overview: Story = { render: () => <EntryOverview entry={entry} /> }',
  ]
  for (const variantId of entry.variantIds) {
    lines.push(`export const Variant${pascal(variantId)}: Story = { name: ${JSON.stringify(variantId)}, render: () => <EntryVariant entry={entry} variantId=${JSON.stringify(variantId)} />, parameters: { docs: { source: { code: entry.variants.find(variant => variant.id === ${JSON.stringify(variantId)})!.code } } } }`)
  }
  files.set(`${family.id}-${entry.entryId}.stories.tsx`, lines.join('\n') + '\n')
}
if (new Set(catalogue.map(item => item.storyId)).size !== entries.length) throw new Error('Duplicate Storybook entry IDs')
files.set('catalogue.generated.json', JSON.stringify(catalogue, null, 2) + '\n')
const figmaLibrary = buildFigmaLibrary(root, catalogue)
files.set('figma-library.generated.json', JSON.stringify(figmaLibrary, null, 2) + '\n')
const canonicalCss = fs.readFileSync(path.join(root, 'apps/mercato/src/app/globals.css'), 'utf8')
const previewCss = canonicalCss
  .replace('@import "tailwindcss";', '@import "tailwindcss" source(none);')
  .replace(/^@import .*module-package-sources\.css.*\n/gm, '')
  .replace(/^@source .*\n/gm, '')
files.set('theme.css', '/* Generated from the canonical app stylesheet by yarn storybook:generate. */\n' + previewCss + '\n@source "../../src";\n@source "../../../core/src/modules/design_system/gallery";\n@source "..";\n')
const check = process.argv.includes('--check')
fs.mkdirSync(output, { recursive: true })
const stale = []
const nativeSourcePath = path.join(root, 'packages/core/src/modules/design_system/gallery/source-library.generated.ts')
const nativeSource = `// Generated by yarn storybook:generate from the shared Figma audit.\nexport const sourceLibrary = ${JSON.stringify(figmaLibrary)}\n`
if (check) {
  if (!fs.existsSync(nativeSourcePath) || fs.readFileSync(nativeSourcePath, 'utf8') !== nativeSource) stale.push('source-library.generated.ts')
} else fs.writeFileSync(nativeSourcePath, nativeSource)
// Complex, interactive examples expose the exact consumer source. Keep their
// copyable code synchronized with the implementation instead of a second demo.
const demoSources = {
  'landing-faq': ['export const landingFaqExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'landing-announcements': ['export const landingAnnouncementExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'landing-pricing': ['export const landingPricingExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'landing-stats': ['export const landingStatsExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'landing-assets': ['export const landingAssetsExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  feeds: [
    'export const activityFeedExampleCode = source + "\\n<ActivityFeedExample />\\n"',
    'export const notificationFeedExampleCode = (tabs: 2 | 3 | 4) => source + `\\n<NotificationFeedExample tabs={${tabs}} />\\n`',
  ],
  'time-picker': ['Status', 'Duration', 'Slot'].map(kind => `export const timePicker${kind}Code = source + "\\n<TimePicker${kind}Examples />\\n"`),
  shell: ['export const shellExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'table-cells': ['export const tableHeaderExampleCode = source + "\\n<TableHeaderExamples />\\n"'],
  'source-filters': ['export const sourceFilterExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'hr-widgets': ['export const hrWidgetExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'finance-widgets': ['export const financeWidgetExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'key-components': ['export const keyComponentExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'marketing-widgets': ['export const marketingWidgetExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'marketing-controls': ['export const marketingControlExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
  'ai-product': ['export const aiProductExampleCode = (expression: string) => source + "\\n" + expression + "\\n"'],
}
for (const [name, declarations] of Object.entries(demoSources)) {
  const sourcePath = path.join(root, `packages/core/src/modules/design_system/gallery/demos/${name}.tsx`)
  if (!fs.existsSync(sourcePath)) continue
  const source = fs.readFileSync(sourcePath, 'utf8')
  const target = sourcePath.replace('.tsx', '-code.generated.ts')
  const contents = `// Generated by yarn storybook:generate from ${name}.tsx.\nconst source = ${JSON.stringify(source)}\n${declarations.join('\n')}\n`
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) stale.push(path.basename(target))
  } else fs.writeFileSync(target, contents)
}
for (const [name, contents] of files) {
  const target = path.join(output, name)
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) stale.push(name)
  } else fs.writeFileSync(target, contents)
}
for (const name of fs.readdirSync(output)) {
  if (files.has(name)) continue
  if (check) stale.push(name)
  else fs.unlinkSync(path.join(output, name))
}
if (stale.length) {
  console.error('Storybook output is stale. Run yarn storybook:generate.', stale)
  process.exitCode = 1
} else console.log(`Storybook: ${families.length} families, ${entries.length} entries, ${entries.reduce((count, entry) => count + entry.variantIds.length, 0)} variants; ${check ? 'in sync' : 'generated'}.`)
