import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import semver from 'semver'
import { parse, stringify } from 'yaml'

const rootDir = fileURLToPath(new URL('../', import.meta.url))
const templatePath = resolve(rootDir, 'packages/create-app/template/yarn.lock.template')

export function buildTemplateEditorLock(lockfileText, dependencies) {
  const lockfile = parse(lockfileText)
  if (!Number.isInteger(lockfile.__metadata?.version)) {
    throw new Error('Root lockfile must declare its Yarn lockfile version')
  }

  const editorEntries = Object.entries(lockfile).filter(([descriptor]) => descriptor.startsWith('@tiptap/'))
  const entriesByName = new Map()
  for (const [descriptor, entry] of editorEntries) {
    const name = entry.resolution?.split('@npm:')[0]
    if (!name?.startsWith('@tiptap/') || !entry.checksum || entry.linkType !== 'hard') {
      throw new Error(`Editor lock entry must be a checksummed npm package: ${descriptor}`)
    }
    if (entriesByName.has(name)) {
      throw new Error(`Editor lock contains ambiguous versions for ${name}`)
    }
    entriesByName.set(name, { descriptors: new Set(descriptor.split(', ')), entry })
  }

  const directDependencies = Object.entries(dependencies).filter(([name]) => name.startsWith('@tiptap/'))
  if (directDependencies.length === 0) throw new Error('Documents must declare its editor dependencies')
  for (const [name, range] of directDependencies) {
    const reviewed = entriesByName.get(name)
    if (!reviewed || !semver.satisfies(reviewed.entry.version, range)) {
      throw new Error(`No reviewed editor resolution satisfies ${name}@${range}`)
    }
    reviewed.descriptors.add(`${name}@npm:${range}`)
  }

  const template = { __metadata: lockfile.__metadata }
  for (const name of [...entriesByName.keys()].sort()) {
    const { descriptors, entry } = entriesByName.get(name)
    template[[...descriptors].sort().join(', ')] = entry
  }
  template['{{APP_NAME}}@workspace:.'] = {
    version: '0.0.0-use.local',
    resolution: '{{APP_NAME}}@workspace:.',
    languageName: 'unknown',
    linkType: 'soft',
  }

  return '# Generated by scripts/sync-template-editor-lock.mjs from the reviewed root yarn.lock.\n'
    + '# Preserves approved editor resolutions while fresh dependencies retain the release-age gate.\n\n'
    + stringify(template, { lineWidth: 0 })
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const lockfile = readFileSync(resolve(rootDir, 'yarn.lock'), 'utf8')
  const documents = JSON.parse(readFileSync(resolve(rootDir, 'packages/documents/package.json'), 'utf8'))
  const generated = buildTemplateEditorLock(lockfile, documents.dependencies)
  if (process.argv.includes('--check')) {
    if (readFileSync(templatePath, 'utf8') !== generated) {
      throw new Error('Template editor lock is stale; run node scripts/sync-template-editor-lock.mjs')
    }
  } else {
    writeFileSync(templatePath, generated)
  }
}
