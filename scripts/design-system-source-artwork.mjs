import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const inputPath = path.join(root, 'packages/ui/src/assets/source-artwork.json')
const input = [
  ...JSON.parse(fs.readFileSync(inputPath, 'utf8')),
  ...JSON.parse(fs.readFileSync(path.join(root, 'packages/ui/src/assets/source-artwork-thumbnails.json'), 'utf8')),
]
const groups = ['brand', 'country-flags', 'emojies', 'appstore-badges', 'others', 'thumbnails']
const expectedCounts = { brand: 439, 'country-flags': 263, emojies: 607, 'appstore-badges': 16, others: 10, thumbnails: 78 }
const ids = new Set()
const rows = []
for (const group of groups) {
  const assets = input.filter(asset => asset.group === group)
  if (assets.length !== expectedCounts[group]) throw new Error(`Incomplete ${group}: ${assets.length}/${expectedCounts[group]}`)
  for (const asset of assets) {
    if (ids.has(asset.id)) throw new Error(`Duplicate artwork ${asset.id}`)
    ids.add(asset.id)
    const bytes = Buffer.from(asset.data, 'base64')
    if (bytes.subarray(1, 4).toString() !== 'PNG') throw new Error(`Invalid PNG ${asset.id}`)
    rows.push({ id: asset.id, group, name: asset.name, category: asset.category, width: asset.width, height: asset.height, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') })
  }
  const records = assets.map(({ data, ...asset }) => ({ ...asset, src: `data:image/png;base64,${data}` }))
  const content = `// Generated by node scripts/design-system-source-artwork.mjs.\nimport type { SourceArtwork } from './source-artwork'\n\nexport const artwork: readonly SourceArtwork[] = ${JSON.stringify(records)}\n`
  const outputPath = path.join(root, `packages/ui/src/assets/source-artwork-${group}.generated.ts`)
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== content) throw new Error(`Stale source artwork: ${group}`)
  } else fs.writeFileSync(outputPath, content)
}
if (!process.argv.includes('--check')) fs.writeFileSync(path.join(root, 'docs/design-system/figma-audit/source-artwork-manifest.json'), JSON.stringify({ source: 'qCq9z6q1if0mpoRstV5OEA', method: 'Read-only PNG export from original Figma nodes: scale 2 for icons and logos; native resolution for thumbnails', count: rows.length, assets: rows }, null, 2) + '\n')
console.log(`Original source artwork: ${rows.length} verified PNGs in ${groups.length} lazy-loaded collections.`)
