import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as lucide from 'lucide-react'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const inventory = JSON.parse(fs.readFileSync(path.join(root, 'docs/design-system/figma-audit/foundations-assets.json')))
const page = inventory.pages.find(item => item.slug === 'icons')
const artwork = JSON.parse(fs.readFileSync(path.join(root, 'packages/ui/src/assets/source-icon-artwork.json')))
const original = new Map(artwork.map(item => [item.name, item]))
const pascal = name => name.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('')
const names = [...new Set(page.iconFrames.map(item => item[1]).filter(name => name.startsWith('li:')).map(name => name.slice(3)))].sort((first, second) => first.localeCompare(second))
const missing = names.filter(name => !lucide[pascal(name)] && !original.has(name))
if (missing.length) throw new Error(`Source icons lack a Lucide export or original artwork: ${missing.join(', ')}`)
const runtime = names.filter(name => lucide[pascal(name)])
const contents = `// Generated by node scripts/design-system-source-icons.mjs from the Figma inventory.\nimport { ${runtime.map(pascal).join(', ')} } from 'lucide-react'\n\nexport const sourceLucideIcons = {\n${runtime.map(name => `  ${JSON.stringify(name)}: ${pascal(name)},`).join('\n')}\n} as const\n\nexport const sourceIconNames = ${JSON.stringify(names, null, 2)} as const\nexport type SourceIconName = typeof sourceIconNames[number]\n`
const output = path.join(root, 'packages/ui/src/assets/source-icons.generated.ts')
const withArtwork = contents + `\nexport const originalSourceIconArtwork = ${JSON.stringify(artwork)} as const\n`
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== withArtwork) throw new Error('Source icon catalogue is stale; run node scripts/design-system-source-icons.mjs')
} else fs.writeFileSync(output, withArtwork)
console.log(`Source icon catalogue: ${names.length} icons, ${runtime.length} Lucide components, ${names.length - runtime.length} original Figma SVGs.`)
