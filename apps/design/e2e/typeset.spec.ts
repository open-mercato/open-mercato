import { expect, test } from '@playwright/test'

test('typeset exports the displayed settings and fits a narrow document', async ({ page, context }) => {
  const origin = process.env.OM_DESIGN_URL ?? 'http://localhost:3020'
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin })
  await page.goto(new URL('/foundations/typeset/', origin).href)
  const studio = page.frameLocator('iframe[title="Typeset studio example"]')
  await expect(studio.getByRole('rowheader', { name: 'Total' })).toBeVisible()
  await studio.getByRole('radio', { name: 'Document' }).click()
  await studio.getByRole('combobox', { name: 'Text size' }).selectOption('20')
  await studio.getByRole('combobox', { name: 'Line height' }).selectOption('1.8')
  await studio.getByRole('combobox', { name: 'Line length' }).selectOption('48')
  const article = studio.getByRole('article')
  await expect(article).toHaveCSS('font-size', '20px')
  await expect(article).toHaveCSS('line-height', '36px')
  await studio.getByRole('button', { name: 'Copy CSS' }).click()
  await expect(studio.getByRole('status')).toHaveText('Stylesheet copied.')
  const css = await page.evaluate(() => navigator.clipboard.readText())
  expect(css).toContain('.om-typeset-document {')
  expect(css).toContain('--om-type-size: 1.25rem')
  expect(css).toContain('--om-type-leading: 1.8')
  expect(css).toContain('--om-type-measure: 48ch')
  await studio.getByRole('radio', { name: 'Work order' }).click()
  await expect(article).toHaveCSS('font-size', '16px')
  await studio.getByRole('radio', { name: 'Document' }).click()
  await expect(article).toHaveCSS('font-size', '20px')
  await page.setViewportSize({ width: 390, height: 844 })
  await article.evaluate(element => { element.ownerDocument.documentElement.style.fontSize = '200%' })
  await expect(article).toHaveCSS('font-size', '40px')
  expect(await article.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
})
